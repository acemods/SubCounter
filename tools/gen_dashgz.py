#!/usr/bin/env python3
"""Make a12z_dashgz.ino: the dashboard page (DASH_HTML in a13_web.ino) gzip-compressed,
so the board sends ~12 KB instead of ~37 KB. Run it after changing DASH_HTML:

    python3 tools/gen_dashgz.py firmware/SubCounter

If you forget, nothing breaks: the board notices the sizes don't match and sends the
uncompressed page instead."""
import gzip, sys, os
d = sys.argv[1] if len(sys.argv) > 1 else 'firmware/SubCounter'
s = open(os.path.join(d, 'a13_web.ino'), encoding='utf-8').read()
key = '#define ICON_LINKS "'
links = s[s.index(key) + len(key):]
links = links[:links.index('"\n')]
start = 'const char DASH_HTML[] PROGMEM = R"HTML('
i = s.index(start) + len(start)
body = s[i:s.index(')HTML";', i)].replace(')HTML" ICON_LINKS R"HTML(', links).encode('utf-8')
gz = gzip.compress(body, 9, mtime=0)
rows = [', '.join('0x%02x' % b for b in gz[k:k + 24]) for k in range(0, len(gz), 24)]
out = ('// Generated by tools/gen_dashgz.py from DASH_HTML in a13_web.ino - do not edit by hand.\n'
       '// The dashboard page, gzip-compressed (%d -> %d bytes).\n'
       '#define DASH_GZ_SRC_LEN %d\n'
       'const uint8_t DASH_GZ[] PROGMEM = {\n  %s\n};\n') % (len(body), len(gz), len(body), ',\n  '.join(rows))
open(os.path.join(d, 'a12z_dashgz.ino'), 'w').write(out)
print('dashboard %d -> %d bytes' % (len(body), len(gz)))
